"""Build `sampling_regions_v3.json`: the v1 sampling regions cut at state AND timezone lines.

v1 maps 3,084 non-California county GISJOINs to 50 regions (0-49). California is handled
separately in code, where CEC climate zones map tracts to regions 100-110; those are already
inside one state and one timezone, and v3 leaves them untouched.

Two defects motivate the cut, measured on the run that exists:

  * 25.7% of allocated dwelling units are simulated in a state other than the one they live in,
    because 28 of the 50 v1 regions straddle a state line.
  * 5.8% are simulated in the wrong timezone, almost symmetrically (3.97M an hour late, 3.96M an
    hour early), which leaves national load shapes roughly intact but distorts state and utility
    ones. Cutting at state lines alone fixes only about 40% of this: 24 of the 106 state-cut
    pieces still straddle a zone line, holding 24.3% of the stock.

v3 is a pure refinement of v1 on both axes:

    v3_id = state_fips * 10000 + abs(utc_offset) * 100 + v1_id

so `v3_id % 100` reproduces v1 exactly, `(v3_id % 10000) // 100` is the standard UTC offset, and
`v3_id // 10000` is the state FIPS. Ids run 10600-560749, clear of the California ids 100-110.
(v2, the state-only cut, used `state_fips * 1000 + v1_id`; the schemes are not nested.)

Timezone comes from the LOCATION header of the AMY2018 EPW actually used for each county, so it is
the offset the simulation ran in rather than a civil-time convention. These are standard-time
offsets: Arizona is indistinguishable from Mountain, which is correct here because the runs use
standard time throughout. The derived crosswalk is written to `county_timezone_amy2018.csv` and
reused on later runs, so the weather files are only needed once.

The same relabelling is applied to `Sampling Region.tsv`, so the sampler segments on the ids the
allocator joins on. That file is normally generated by resstock-estimation
`sources/spatial/tsv_maker.py`; relabelling it here is mechanical rather than a regeneration,
because each row has exactly one hot option and Void rows pass through. No prune rule, source
count, source weight or sampling probability is touched.

Writes: sampling_regions_v3.json
        Sampling Region v3.tsv               (v3 option columns)
        county_timezone_amy2018.csv          (GISJOIN -> UTC offset, from the EPW headers)
        sampling_regions_v3_crosswalk.csv    (county-level review table)
        sampling_regions_v3_validation.txt   (the checks below)
"""
import csv
import glob
import io
import json
import os
import sys
from collections import Counter

import polars as pl

HERE = os.path.dirname(os.path.abspath(__file__))
RUN = "C:/Scratch/ResStock/efforts/new_sampling/new_sampling_test_4_output"
REPO = "C:/GitRepos/resstock/.claude/worktrees/kind-noether-53b4ec"
V1_JSON = os.path.join(RUN, "sampling_regions_v1.json")
V1_TSV = os.path.join(HERE, "_sampling_region_v1_source.tsv")
CAT = os.path.join(RUN, "cached_catalogue_by_sampling_region", "*", "*.parquet")
NAME_LKUP = os.path.join(REPO, "postprocessing/resstockpostproc/resources/gisdata/"
                               "county_lookup_table.csv")
EPW_DIR = "C:/Projects/WeatherData/BuildStock_2018_FIPS_HI"
TZ_CSV = os.path.join(HERE, "county_timezone_amy2018.csv")

# resstockpostproc.allocated_weights.load_sampling_regions patches this county in after loading
# v1, because v1 predates the Shannon -> Oglala Lakota rename. v3 carries it properly, so that
# patch must become a setdefault or it will force the county into a non-existent region.
OGLALA, OGLALA_V1 = "G4601020", 34
TAB, NL = chr(9), chr(10)

out = []


def say(line=""):
    print(line)
    out.append(line)


def county_timezones():
    """GISJOIN -> standard UTC offset, from the LOCATION line of each county's AMY2018 EPW."""
    if os.path.exists(TZ_CSV):
        d = pl.read_csv(TZ_CSV)
        return {r["county_gisjoin"]: int(r["utc_offset"]) for r in d.iter_rows(named=True)}
    rows = []
    for p in sorted(glob.glob(os.path.join(EPW_DIR, "*.epw"))):
        with open(p, "r", errors="replace") as f:
            loc = f.readline().split(",")
        rows.append({"county_gisjoin": os.path.basename(p)[:-4], "utc_offset": int(float(loc[8]))})
    if not rows:
        raise SystemExit("no EPW files under {} and no {}".format(EPW_DIR, TZ_CSV))
    pl.DataFrame(rows).sort("county_gisjoin").write_csv(TZ_CSV)
    return {r["county_gisjoin"]: r["utc_offset"] for r in rows}


def tsv_county_regions():
    """County GISJOIN -> v1 region, as `Sampling Region.tsv` itself assigns it.

    California counties are skipped: their regions (100-110) come from CEC tracts in code, not
    from the county JSON, and a California county legitimately appears under several of them.
    """
    name_to_cg = {}
    with open(NAME_LKUP, encoding="utf-8-sig", newline="") as f:
        for r in csv.DictReader(f):
            name_to_cg[r["long_name"]] = r["original_FIP"]
    lines = [ln.rstrip(chr(13)) for ln in io.open(V1_TSV, encoding="utf-8").read().split(NL)
             if ln.strip() and not ln.startswith("#")]
    head = lines[0].split(TAB)
    opts = [(i, h[len("Option="):]) for i, h in enumerate(head) if h.startswith("Option=")]
    cty = head.index("Dependency=County")
    found = {}
    for ln in lines[1:]:
        c = ln.split(TAB)
        hot = [o for i, o in opts if c[i] not in ("0", "0.0", "")]
        if len(hot) != 1 or hot[0] == "Void" or int(hot[0]) >= 100:
            continue
        cg = name_to_cg.get(c[cty])
        if cg is not None:
            found[cg] = int(hot[0])
    return found


def main():
    with open(V1_JSON) as f:
        v1 = dict(json.load(f))
    if OGLALA not in v1:
        v1[OGLALA] = OGLALA_V1

    tz = county_timezones()
    say("=== inputs ===")
    say("  v1 counties {:,} in {} regions".format(len(v1), len(set(v1.values()))))
    say("  timezone crosswalk: {:,} counties, offsets {}".format(
        len(tz), sorted(set(tz.values()))))

    # Counties the local weather set has no file for, and counties v1 codes under a retired FIPS
    # while the TSV uses the current one (Alaska's Wade Hampton / Kusilvak is both), fall back to
    # the state's own modal offset. That is right everywhere except Aleutians West, named above.
    by_state = {}
    for cg, z in tz.items():
        by_state.setdefault(cg[1:3], Counter())[z] += 1
    fallbacks = {}

    def offset(cg):
        """Standard UTC offset for a county, falling back to its state's modal offset."""
        if cg not in tz:
            tz[cg] = by_state[cg[1:3]].most_common(1)[0][0]
            fallbacks[cg] = tz[cg]
        return tz[cg]

    # v1 carries two retired county codes (Wade Hampton G0202700, Shannon G4601130) and is
    # missing the current code for each rename. The TSV is generated from the current county
    # universe, so any non-California county it places in a region but v1 does not know about is
    # added here with the region the TSV itself gives. Without this the sampler can draw
    # buildings in a county the allocator never assigns units to, and those simulations are
    # simply wasted. The retired codes are kept as harmless aliases.
    added = {}
    for cg, rid in tsv_county_regions().items():
        if cg not in v1:
            v1[cg] = rid
            added[cg] = rid

    # ---- the JSON ----------------------------------------------------------
    v3 = {}
    for cg, rid in v1.items():
        st, z = int(cg[1:3]), offset(cg)
        v3[cg] = st * 10000 + abs(z) * 100 + int(rid)
    if added:
        say()
        say("=== counties the TSV places in a region but v1 omits ===")
        for cg, rid in sorted(added.items()):
            say("  {} -> v1 region {}, v3 {}".format(cg, rid, v3[cg]))
    with open(os.path.join(HERE, "sampling_regions_v3.json"), "w") as f:
        json.dump(v3, f, indent=1, sort_keys=True)

    say()
    say("=== sampling_regions_v3.json ===")
    say("  counties            v1 {:>6,}  v3 {:>6,}".format(len(v1), len(v3)))
    say("  regions             v1 {:>6,}  v3 {:>6,}".format(
        len(set(v1.values())), len(set(v3.values()))))
    say("  id range            v1 {}-{}   v3 {}-{}".format(
        min(v1.values()), max(v1.values()), min(v3.values()), max(v3.values())))
    say("  Oglala Lakota {}: v1 {} -> v3 {}".format(OGLALA, v1[OGLALA], v3[OGLALA]))

    say()
    say("=== checks ===")
    say("  [{}] v3 % 100 reproduces v1 for every county ({} mismatches)".format(
        *(lambda b: ("ok" if not b else "FAIL", len(b)))(
            [cg for cg in v1 if v3[cg] % 100 != v1[cg]])))
    say("  [{}] (v3 % 10000) // 100 recovers the county's own offset".format(
        "ok" if all((v3[cg] % 10000) // 100 == abs(tz[cg]) for cg in v3) else "FAIL"))
    say("  [{}] v3 // 10000 recovers the county's own state FIPS".format(
        "ok" if all(v3[cg] // 10000 == int(cg[1:3]) for cg in v3) else "FAIL"))
    span_s, span_z = {}, {}
    for cg, rid in v3.items():
        span_s.setdefault(rid, set()).add(cg[1:3])
        span_z.setdefault(rid, set()).add(tz[cg])
    say("  [{}] no v3 region spans more than one state ({} do)".format(
        *(lambda n: ("ok" if not n else "FAIL", n))(
            sum(1 for s in span_s.values() if len(s) > 1))))
    say("  [{}] no v3 region spans more than one timezone ({} do)".format(
        *(lambda n: ("ok" if not n else "FAIL", n))(
            sum(1 for s in span_z.values() if len(s) > 1))))
    clash = sorted(set(v3.values()) & set(range(100, 111)))
    say("  [{}] no v3 id collides with the California ids 100-110 ({})".format(
        "ok" if not clash else "FAIL", clash or "none"))

    # ---- against the catalogue --------------------------------------------
    agg = (pl.scan_parquet(CAT)
           .select(pl.col("in.nhgis_county_gisjoin").alias("cg"),
                   pl.col("in.sampling_region_id").cast(pl.Int32).alias("v1"),
                   pl.col("in.state").alias("state"))
           .group_by(["cg", "v1", "state"]).agg(pl.len().alias("units"))
           .collect(engine="streaming"))
    tot = agg["units"].sum()
    ca = agg.filter(pl.col("v1") >= 100)
    mapped = (agg.filter(pl.col("v1") < 100)
              .join(pl.DataFrame({"cg": list(v3.keys()), "v3": list(v3.values())}),
                    on="cg", how="left"))
    unmapped = mapped.filter(pl.col("v3").is_null())
    say()
    say("=== coverage against the ACS catalogue ===")
    say("  catalogue housing units                   {:>14,}".format(tot))
    say("  in California regions 100-110, untouched  {:>14,}".format(ca["units"].sum()))
    say("  [{}] non-California units with no v3 county: {:,} in {} counties".format(
        "ok" if unmapped.height == 0 else "FAIL", unmapped["units"].sum(), unmapped.height))

    pieces = (mapped.filter(pl.col("v3").is_not_null())
              .group_by("v3").agg(pl.col("units").sum(),
                                  pl.col("cg").n_unique().alias("counties"))
              .sort("units"))
    say()
    say("=== region count ===")
    say("  v1 non-California                {:>4}".format(
        agg.filter(pl.col("v1") < 100)["v1"].n_unique()))
    say("  v3 non-California                {:>4}".format(pieces.height))
    say("  California, unchanged            {:>4}".format(ca["v1"].n_unique()))
    say("  v3 total                         {:>4}".format(pieces.height + ca["v1"].n_unique()))
    say()
    say("=== every piece below 0.1% of national housing units ===")
    say("  {:>9} {:>8} {:>7} {:>9} {:>14} {:>10}".format(
        "v3 id", "state", "offset", "counties", "units", "share"))
    for r in pieces.filter(pl.col("units") / tot < 1e-3).iter_rows(named=True):
        say("  {:>9} {:>8} {:>7} {:>9,} {:>14,} {:>9.4f}%".format(
            r["v3"], r["v3"] // 10000, -((r["v3"] % 10000) // 100), r["counties"], r["units"],
            r["units"] / tot * 100))
    say("  pieces below 0.01%: {}; below 0.1%: {}".format(
        int((pieces["units"] / tot < 1e-4).sum()), int((pieces["units"] / tot < 1e-3).sum())))
    say("  smallest {:,} units; median {:,.0f}; largest {:,}".format(
        pieces["units"].min(), pieces["units"].median(), pieces["units"].max()))

    cw = (mapped.filter(pl.col("v3").is_not_null())
          .with_columns(pl.col("cg").replace_strict(tz, default=None).alias("utc_offset"))
          .select("cg", "state", "utc_offset", pl.col("v1").alias("v1_region"),
                  pl.col("v3").alias("v3_region"), "units")
          .sort(["v1_region", "state", "cg"]))
    cw.write_csv(os.path.join(HERE, "sampling_regions_v3_crosswalk.csv"))
    say()
    say("  wrote sampling_regions_v3_crosswalk.csv ({:,} counties)".format(cw.height))

    if fallbacks:
        say()
        say("=== counties given their state's modal offset ===")
        for cg, z in sorted(fallbacks.items()):
            say("  {} state {} -> offset {}".format(cg, cg[1:3], z))

    relabel_tsv(v3, offset)

    with open(os.path.join(HERE, "sampling_regions_v3_validation.txt"), "w") as f:
        f.write(NL.join(out) + NL)


def relabel_tsv(v3, offset):
    """Rewrite `Sampling Region.tsv` so its one-hot option columns carry the v3 ids."""
    name_to_cg = {}
    with open(NAME_LKUP, encoding="utf-8-sig", newline="") as f:
        for r in csv.DictReader(f):
            name_to_cg[r["long_name"]] = r["original_FIP"]

    with open(V1_TSV, newline="") as f:
        lines = [ln.rstrip(chr(13)) for ln in f.read().split(NL)]
    comments = [ln for ln in lines if ln.startswith("#")]
    body = [ln for ln in lines if ln.strip() and not ln.startswith("#")]
    head = body[0].split(TAB)
    rows = [ln.split(TAB) for ln in body[1:]]

    opt_idx = [i for i, h in enumerate(head) if h.startswith("Option=")]
    opts = [head[i][len("Option="):] for i in opt_idx]
    dep_idx = [i for i, h in enumerate(head) if h.startswith("Dependency=")]
    tail_idx = [i for i, h in enumerate(head)
                if not h.startswith("Option=") and not h.startswith("Dependency=")]
    cty_col = head.index("Dependency=County")

    zero = ("0", "0.0", "")
    new_opts, per_row, unknown = set(), [], set()
    for r in rows:
        hot = [k for k, i in enumerate(opt_idx) if r[i] not in zero]
        if len(hot) != 1:
            raise SystemExit("row is not one-hot: {}".format(r[:2]))
        o = opts[hot[0]]
        if o == "Void" or int(o) >= 100:
            new = o                                   # Void and California pass through
        else:
            cg = name_to_cg.get(r[cty_col])
            if cg is None:
                unknown.add(r[cty_col])
                new = o
            else:
                new = str(int(cg[1:3]) * 10000 + abs(offset(cg)) * 100 + int(o))
        per_row.append((r, new, r[opt_idx[hot[0]]]))
        new_opts.add(new)
    if unknown:
        raise SystemExit("county names absent from county_lookup_table.csv: {}".format(
            sorted(unknown)[:5]))

    order = sorted(new_opts, key=lambda o: (1, 0) if o == "Void" else (0, int(o)))
    pos = {o: k for k, o in enumerate(order)}
    out_head = ([head[i] for i in dep_idx] + ["Option=" + o for o in order]
                + [head[i] for i in tail_idx])
    out_rows = []
    for r, new, val in per_row:
        cells = ["0"] * len(order)
        cells[pos[new]] = val
        out_rows.append([r[i] for i in dep_idx] + cells + [r[i] for i in tail_idx])

    # v1 puts the header on line 1 and its four `#` comment lines at the END of the file, with
    # no trailing newline. ResStock reads line 1 as the header, so comments at the top make it
    # parse a comment as the header and fail on the first data row. Reproduce v1 exactly.
    body = [TAB.join(out_head)] + [TAB.join(r) for r in out_rows] + comments
    with open(os.path.join(HERE, "Sampling Region v3.tsv"), "w", newline="") as f:
        f.write(NL.join(body))

    nd = len(dep_idx)
    say()
    say("=== Sampling Region v3.tsv ===")
    say("  rows {:,} (unchanged); comment lines {}".format(len(out_rows), len(comments)))
    say("  option columns  v1 {:>4}  ->  v3 {:>4}".format(len(opts), len(order)))
    say("  passed through unchanged: {}".format(
        [o for o in order if o == "Void" or int(o) < 10000]))
    say("  [{}] every row still one-hot".format(
        "ok" if all(sum(1 for c in r[nd:nd + len(order)] if c not in zero) == 1
                    for r in out_rows) else "FAIL"))
    tsv_ids = set(o for o in order if o != "Void" and int(o) >= 10000)
    json_ids = set(str(v) for v in v3.values())
    say("  [{}] every id the sampler can assign exists for the allocator ({} would be orphaned)"
        .format("ok" if tsv_ids <= json_ids else "FAIL", len(tsv_ids - json_ids)))
    only_json = sorted(json_ids - tsv_ids, key=int)
    say("  {} id(s) in the JSON that the TSV never assigns: {}".format(
        len(only_json), only_json or "none"))
    say("    (these come from the retired county codes v1 carries as aliases; no catalogue row"
        " reaches them)" if only_json else "")
    say("  [{}] row probabilities preserved cell for cell".format(
        "ok" if all(a[2] == b[pos[a[1]] + nd] for a, b in zip(per_row, out_rows)) else "FAIL"))


if __name__ == "__main__":
    sys.exit(main())
